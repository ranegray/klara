#!/usr/bin/env python3
"""Mount Isaac Sim's RealSense D455 stack at Klara's URDF camera frame.

Isaac Sim 6 does not provide a D435if asset.  Its certified D455 asset is used
as the closest built-in approximation and is referenced below the imported
``head_camera_link``.  The D455 asset keeps its own housing geometry, stereo
baseline, calibrated cameras, and depth-sensor schemas.  The overlapping
``tophead6`` visual meshes are removed from the Isaac USD during configuration.
An ActionGraph publishes its color image, depth image, camera calibration, and
depth-derived point cloud through the Isaac ROS 2 bridge.

Run this after ``import_klara.py`` with Isaac Sim's Python launcher::

    ~/isaacsim/python.sh assets/usd/configure_realsense.py

The default mount transform is identity so the sensor is coincident with
``head_camera_link``.  Optional local offsets can still be supplied for
visual/mechanical fine-tuning::

    ~/isaacsim/python.sh assets/usd/configure_realsense.py \
        --translation 0 0 0 --rotation-deg 0 0 0
"""

