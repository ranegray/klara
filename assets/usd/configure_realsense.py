def export_stage_atomically(stage: object, usd_path: Path) -> None:
    original_mode = usd_path.stat().st_mode & 0o777
    with tempfile.NamedTemporaryFile(
        dir=usd_path.parent,
        prefix=f".{usd_path.stem}.",
        suffix=usd_path.suffix,
        delete=False,
    ) as temporary_output:
        temporary_path = Path(temporary_output.name)
    try:
        if not stage.GetRootLayer().Export(str(temporary_path)):
            raise RuntimeError(f"failed to export configured USD to {temporary_path}")
        temporary_path.chmod(original_mode)
        os.replace(temporary_path, usd_path)
    finally:
        temporary_path.unlink(missing_ok=True)


def configure_usd(
    usd_path: Path,
    translation: tuple[float, ...],
    rotation: tuple[float, ...],
    windowed: bool,
) -> None:
    if not usd_path.is_file():
        raise ValueError(f"USD does not exist: {usd_path}")

    try:
        from isaacsim.simulation_app import SimulationApp
    except ModuleNotFoundError as error:
        raise RuntimeError(
            "Isaac Sim is not available. Run this script with Isaac Sim's ./python.sh."
        ) from error

    simulation_app = SimulationApp({"headless": not windowed})
    try:
        import omni.kit.app
        import omni.usd

        extension_manager = omni.kit.app.get_app().get_extension_manager()
        for extension in REQUIRED_EXTENSIONS:
            if not extension_manager.is_extension_enabled(extension):
                extension_manager.set_extension_enabled_immediate(extension, True)
                simulation_app.update()

        context = omni.usd.get_context()
        if not context.open_stage(str(usd_path)):
            raise RuntimeError(f"Isaac Sim could not open USD: {usd_path}")
        simulation_app.update()
        stage = context.get_stage()
        if stage is None:
            raise RuntimeError(f"Isaac Sim did not create a stage for: {usd_path}")

        removed_tophead6_meshes = remove_tophead6_visual(stage)
        create_mount(stage, translation, rotation)
        asset_url = add_d455_asset(stage)
        attach_d455_to_mount(stage)
        configure_camera_rates(stage)
        configure_ros_graph(stage)
        export_stage_atomically(stage, usd_path)

        print(f"Mounted Isaac Sim RealSense D455 in {usd_path}", flush=True)
        print(f"URDF frame: {HEAD_CAMERA_LINK}", flush=True)
        print(f"Sensor root: {SENSOR_ROOT}", flush=True)
        print(f"Asset: {asset_url}", flush=True)
        print(f"Attached body override: {D455_BODY} rigidBodyEnabled=false", flush=True)
        print(
            f"ROS 2 camera graph: {ROS_GRAPH}; {CAMERA_WIDTH}x{CAMERA_HEIGHT} "
            f"at {CAMERA_RATE_HZ:g} Hz",
            flush=True,
        )
        print(f"  {COLOR_IMAGE_TOPIC}", flush=True)
        print(f"  {COLOR_INFO_TOPIC}", flush=True)
        print(f"  {DEPTH_IMAGE_TOPIC}", flush=True)
        print(f"  {DEPTH_INFO_TOPIC}", flush=True)
        print(f"  {POINTCLOUD_TOPIC}", flush=True)
        print("  /clock", flush=True)
        print("  /tf (articulation and live camera mount)", flush=True)
        print("  /tf_static (base, head-camera, and RealSense frames)", flush=True)
        print(
            f"Removed tophead6 visual meshes: {len(removed_tophead6_meshes)}",
            flush=True,
        )
        print(
            f"Local mount: translation={tuple(translation)} m, "
            f"rotation_xyz={tuple(rotation)} deg",
            flush=True,
        )
    finally:
        simulation_app.close()


def main() -> int:
    args = parse_args()
    usd_path = args.usd.expanduser().resolve()
    try:
        configure_usd(
            usd_path,
            tuple(args.translation),
            tuple(args.rotation_deg),
            args.windowed,
        )
    except (RuntimeError, ValueError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
