def require_prim(stage: object, path: str) -> object:
    prim = stage.GetPrimAtPath(path)
    if not prim.IsValid():
        raise RuntimeError(f"required USD prim is missing: {path}")
    return prim


def remove_tophead6_visual(stage: object) -> list[str]:
    """Remove tophead6's render meshes but preserve its imported fixed link.

    The separate ``head_tilt_link_geom_1`` link has no collision geometry and
    exists only to carry the tophead6 visual.  Keeping the empty link avoids
    leaving its imported fixed joint with a missing body.
    """
    from pxr import Usd, UsdGeom

    tophead6_link = require_prim(stage, TOPHEAD6_LINK)
    mesh_paths = [
        str(prim.GetPath())
        for prim in Usd.PrimRange(tophead6_link)
        if prim.IsA(UsdGeom.Mesh)
    ]
    for mesh_path in sorted(mesh_paths, key=len, reverse=True):
        stage.RemovePrim(mesh_path)
    return mesh_paths


def create_mount(
    stage: object,
    translation: tuple[float, ...],
    rotation: tuple[float, ...],
) -> None:
    from pxr import Gf, Sdf, UsdGeom

    require_prim(stage, HEAD_CAMERA_LINK)
    if stage.GetPrimAtPath(MOUNT_PRIM).IsValid():
        # The script owns this narrowly scoped subtree.  Rebuilding it makes
        # reruns deterministic and prevents duplicate referenced sensors.
        stage.RemovePrim(MOUNT_PRIM)

    mount = UsdGeom.Xform.Define(stage, MOUNT_PRIM)
    mount.AddTranslateOp().Set(Gf.Vec3d(*translation))
    mount.AddRotateXYZOp().Set(Gf.Vec3f(*rotation))
    mount.GetPrim().CreateAttribute(
        "isaac:nameOverride",
        Sdf.ValueTypeNames.String,
        custom=True,
    ).Set(CAMERA_LINK_FRAME)


def add_d455_asset(stage: object) -> str:
    from isaacsim.storage.native import get_assets_root_path
    from pxr import UsdGeom

    # Do not make configuration depend on a renderer, GPU, or an asset-server
    # health check.  Isaac resolves this reference when the stage is opened in
    # the normal simulator environment.
    assets_root = get_assets_root_path(skip_check=True)
    if not assets_root:
        raise RuntimeError("Isaac Sim assets root is unavailable")
    asset_url = assets_root.rstrip("/") + D455_ASSET_PATH

    # Isaac's sensor menu ultimately adds this same USD reference.  Keeping it
    # as a reference preserves the complete housing, calibrated camera prims,
    # stereo baseline, RenderProducts, and depth-sensor API schemas.
    sensor_root = UsdGeom.Xform.Define(stage, SENSOR_ROOT).GetPrim()
    sensor_root.GetReferences().AddReference(asset_url)
    return asset_url


def attach_d455_to_mount(stage: object) -> None:
    """Disable the asset's free rigid body so it follows head_camera_link."""
    from pxr import Sdf

    # The stock D455 authors RSD455 as a dynamic rigid body.  A transform
    # parent does not weld a dynamic body to the robot during simulation.
    # This local override turns it back into mounted geometry without editing
    # NVIDIA's referenced asset.
    body = stage.OverridePrim(D455_BODY)
    body.CreateAttribute(
        "physics:rigidBodyEnabled",
        Sdf.ValueTypeNames.Bool,
        custom=False,
    ).Set(False)


def configure_camera_rates(stage: object) -> None:
    """Match the 6 Hz stream rate used by the physical-camera configuration."""
    from pxr import Sdf

    for camera_path in (COLOR_CAMERA, DEPTH_CAMERA):
        camera = stage.OverridePrim(camera_path)
        camera.CreateAttribute(
            "omni:sensor:tickRate",
            Sdf.ValueTypeNames.Float,
            custom=False,
        ).Set(CAMERA_RATE_HZ)


